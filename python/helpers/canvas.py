async def get_room_manager() -> RoomManager:
    """Get the room manager singleton."""
    return await RoomManager.get_instance()


async def create_room(name: str = "") -> ConversationRoom:
    """Create a new conversation room."""
    manager = await get_room_manager()
    return await manager.create_room(name)


async def get_room(room_id: str) -> Optional[ConversationRoom]:
    """Get a room by ID."""
    manager = await get_room_manager()
    return await manager.get_room(room_id)
