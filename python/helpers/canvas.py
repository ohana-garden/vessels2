@dataclass
class CanvasElement:
    """A visual element on the canvas."""
    id: str
    content_type: CanvasContentType
    content: Dict[str, Any]  # Type-specific content data
    priority: int = 0        # Higher = more prominent
    duration: Optional[float] = None  # Auto-dismiss after seconds
    triggered_by: str = ""   # Participant ID that triggered this
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "contentType": self.content_type.value,
            "content": self.content,
            "priority": self.priority,
            "duration": self.duration,
            "triggeredBy": self.triggered_by,
            "createdAt": self.created_at.isoformat(),
        }

    @classmethod
    def from_dict(cls, data: dict) -> "CanvasElement":
        return cls(
            id=data["id"],
            content_type=CanvasContentType(data["contentType"]),
            content=data["content"],
            priority=data.get("priority", 0),
            duration=data.get("duration"),
            triggered_by=data.get("triggeredBy", ""),
            created_at=datetime.fromisoformat(data["createdAt"]) if "createdAt" in data else datetime.now(timezone.utc),
        )


