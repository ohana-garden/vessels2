@dataclass
class SpeakerStyle:
    """Visual styling for a speaker's subtitles."""
    color: str = "#ffffff"
    background: str = "rgba(0,0,0,0.7)"
    font_weight: str = "normal"
    font_style: str = "normal"
    icon: str = ""
    position: str = "bottom"  # bottom, top, left, right

    def to_dict(self) -> dict:
        return {
            "color": self.color,
            "background": self.background,
            "fontWeight": self.font_weight,
            "fontStyle": self.font_style,
            "icon": self.icon,
            "position": self.position,
        }


@dataclass
class Participant:
    """Base class for all conversation participants."""
    id: str
    name: str
    participant_type: ParticipantType
    style: SpeakerStyle = field(default_factory=SpeakerStyle)
    voice_id: str = ""  # For TTS voice selection
    personality: str = ""  # Brief personality description
    knowledge_areas: List[str] = field(default_factory=list)
    active: bool = True

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "name": self.name,
            "type": self.participant_type.value,
            "style": self.style.to_dict(),
            "voiceId": self.voice_id,
            "personality": self.personality,
            "knowledgeAreas": self.knowledge_areas,
            "active": self.active,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "Participant":
        style_data = data.get("style", {})
        return cls(
            id=data["id"],
            name=data["name"],
            participant_type=ParticipantType(data.get("type", "entity_agent")),
            style=SpeakerStyle(**style_data) if style_data else SpeakerStyle(),
            voice_id=data.get("voiceId", ""),
            personality=data.get("personality", ""),
            knowledge_areas=data.get("knowledgeAreas", []),
            active=data.get("active", True),
        )


@dataclass
class HumanProxy(Participant):
    """Represents a human in a specific role."""
    human_id: str = ""  # Links to the actual human
    role: str = ""      # The role they're playing (gardener, coordinator, etc.)
    can_barge_in: bool = True

    def __post_init__(self):
        self.participant_type = ParticipantType.HUMAN_PROXY
        if not self.style.color:
            self.style.color = "#4ade80"  # Green for humans

    def to_dict(self) -> dict:
        base = super().to_dict()
        base.update({
            "humanId": self.human_id,
            "role": self.role,
            "canBargeIn": self.can_barge_in,
        })
        return base


@dataclass
class EntityAgent(Participant):
    """Represents a non-human entity (plant, machine, place, etc.)."""
    entity_kind: EntityKind = EntityKind.PLANT
    entity_data: Dict[str, Any] = field(default_factory=dict)
    location: Optional[Dict[str, float]] = None  # lat, lng
    status: str = "active"
    relationships: List[str] = field(default_factory=list)  # IDs of related entities

    def __post_init__(self):
        self.participant_type = ParticipantType.ENTITY_AGENT
        # Set default colors by entity kind
        kind_colors = {
            EntityKind.PLANT: "#22c55e",      # Green
            EntityKind.CREATURE: "#f59e0b",   # Amber
            EntityKind.MACHINE: "#6366f1",    # Indigo
            EntityKind.PLACE: "#8b5cf6",      # Purple
            EntityKind.BIOME: "#14b8a6",      # Teal
            EntityKind.RESOURCE: "#f97316",   # Orange
            EntityKind.PROCESS: "#06b6d4",    # Cyan
            EntityKind.COLLECTIVE: "#ec4899", # Pink
        }
        if not self.style.color:
            self.style.color = kind_colors.get(self.entity_kind, "#ffffff")

    def to_dict(self) -> dict:
        base = super().to_dict()
        base.update({
            "entityKind": self.entity_kind.value,
            "entityData": self.entity_data,
            "location": self.location,
            "status": self.status,
            "relationships": self.relationships,
        })
        return base


