# Room Manager (Singleton)
# =============================================================================

class RoomManager:
    """Manages all active conversation rooms."""

    _instance: Optional["RoomManager"] = None
    _lock = asyncio.Lock()

    def __init__(self):
        self.rooms: Dict[str, ConversationRoom] = {}
        self._graph_store: Optional[GraphStore] = None

    @classmethod
    async def get_instance(cls) -> "RoomManager":
        """Get the singleton instance."""
        async with cls._lock:
            if cls._instance is None:
                cls._instance = cls()
                cls._instance._graph_store = await get_graph_store()
            return cls._instance

    async def create_room(self, name: str = "") -> ConversationRoom:
        """Create a new conversation room."""
        room_id = guids.generate_id(12)
        room = ConversationRoom(room_id, name)
        self.rooms[room_id] = room
        await self._persist_room(room)
        return room

    async def get_room(self, room_id: str) -> Optional[ConversationRoom]:
        """Get a room by ID."""
        if room_id in self.rooms:
            return self.rooms[room_id]

        # Try to load from graph store
        return await self._load_room(room_id)

    async def get_or_create_room(self, room_id: str, name: str = "") -> ConversationRoom:
        """Get existing room or create new one."""
        room = await self.get_room(room_id)
        if not room:
            room = ConversationRoom(room_id, name)
            self.rooms[room_id] = room
            await self._persist_room(room)
        return room

    async def delete_room(self, room_id: str) -> bool:
        """Delete a room."""
        if room_id in self.rooms:
            del self.rooms[room_id]

        if self._graph_store:
            query = f"""
            MATCH (n:Episode) WHERE n.name = 'room_{room_id}'
            DETACH DELETE n
            """
            try:
                await self._graph_store._driver.execute_query(query)
                return True
            except Exception:
                return False
        return True

    async def _persist_room(self, room: ConversationRoom) -> None:
        """Persist room to graph store."""
        if not self._graph_store:
            return

        from graphiti_core.nodes import EpisodeType

        room_data = json.dumps(room.to_dict())
        await self._graph_store._graphiti.add_episode(
            name=f"room_{room.id}",
            episode_body=room_data,
            source=EpisodeType.json,
            reference_time=room.last_activity,
            group_id="conversation_rooms",
        )

    async def _load_room(self, room_id: str) -> Optional[ConversationRoom]:
        """Load room from graph store."""
        if not self._graph_store:
            return None

        query = f"""
        MATCH (n:Episode) WHERE n.name = 'room_{room_id}'
        RETURN n.content as content
        """
        try:
            result = await self._graph_store._driver.execute_query(query)
            if result and len(result) > 0:
                content = result[0].get("content", "{}")
                data = json.loads(content)
                room = ConversationRoom.from_dict(data)
                self.rooms[room_id] = room
                return room
        except Exception as e:
            PrintStyle.error(f"Failed to load room {room_id}: {e}")

        return None

    def get_all_rooms(self) -> List[ConversationRoom]:
        """Get all active rooms."""
        return list(self.rooms.values())


