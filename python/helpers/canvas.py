class ParticipantType(str, Enum):
    """Types of conversation participants."""
    HUMAN_PROXY = "human_proxy"      # Represents a human in a role
    ENTITY_AGENT = "entity_agent"    # Represents non-human entity
    HUMAN_DIRECT = "human_direct"    # Human speaking directly (barge-in)


class EntityKind(str, Enum):
    """Kinds of entities that can have agents."""
    PLANT = "plant"           # Trees, crops, gardens
    CREATURE = "creature"     # Animals, insects, microbes
    MACHINE = "machine"       # Equipment, vehicles, systems
    PLACE = "place"           # Locations, buildings, regions
    BIOME = "biome"           # Ecosystems, watersheds, soil
    RESOURCE = "resource"     # Food, water, materials
    PROCESS = "process"       # Workflows, cycles, patterns
    COLLECTIVE = "collective" # Groups, communities, networks


class CanvasContentType(str, Enum):
    """Types of content that can appear on the canvas."""
    MAP = "map"                     # Geographic visualization
    CALENDAR = "calendar"           # Time/scheduling view
    VISUALIZATION = "visualization" # Data/charts/graphs
    GALLERY = "gallery"             # Photos/images
    APPLET = "applet"               # Interactive widget
    AMBIENT = "ambient"             # Background/mood imagery
    ENTITY_VIEW = "entity_view"     # Entity status/details
    RELATIONSHIP = "relationship"   # Connection visualization


class EmotionalState(str, Enum):
    """Emotional states detected from voice (Hume.ai integration)."""
    NEUTRAL = "neutral"
    EXCITED = "excited"
    STRESSED = "stressed"
    CONFUSED = "confused"
    FRUSTRATED = "frustrated"
    SATISFIED = "satisfied"
    CURIOUS = "curious"
    URGENT = "urgent"


