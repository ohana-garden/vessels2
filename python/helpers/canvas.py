"""
Vessels Dynamic Canvas System

Voice-first UI where conversation drives everything. Visual content appears
contextually - generated by AI agents in response to what's being discussed.
Movie-style subtitles overlay the content to show who's speaking.

The model:
- Live humans have proxy agents representing them in roles
- Proxies converse with other agents (human proxies or entity agents)
- Entity agents represent non-human things: plants, machines, places, biomes
- Humans can direct their proxy or barge in directly
- All participants react to each other, the canvas, and context
"""

